"""Keep admission held until synchronous dependency work has actually stopped."""

from __future__ import annotations

import asyncio
from collections.abc import Callable
from typing import ParamSpec, TypeVar

P = ParamSpec("P")
T = TypeVar("T")


async def run_blocking(function: Callable[P, T], *args: P.args, **kwargs: P.kwargs) -> T:
    """Offload blocking work without releasing admission on caller cancellation.

    Python threads cannot be forcibly canceled. Shield the worker and wait for
    its completion even when the requesting task is canceled more than once.
    Process shutdown and dependency timeouts still need operational controls.
    """
    worker = asyncio.create_task(asyncio.to_thread(function, *args, **kwargs))
    try:
        return await asyncio.shield(worker)
    except asyncio.CancelledError:
        while not worker.done():
            try:
                await asyncio.shield(worker)
            except asyncio.CancelledError:
                continue
            except Exception:
                break
        if not worker.cancelled():
            worker.exception()
        raise
